import { normalizePointcloud, type PPoint, type PTemplate } from './dollarP';

type RawStroke = [number, number][];

function toPoints(strokes: RawStroke[]): PPoint[] {
  const pts: PPoint[] = [];
  strokes.forEach((stroke, strokeId) => {
    stroke.forEach(([x, y]) => {
      pts.push({ x, y, strokeId });
    });
  });
  return pts;
}

