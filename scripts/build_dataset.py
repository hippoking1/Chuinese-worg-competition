def make_rows(dataset, q_type, year):
    rows = []
    type_code = "S" if q_type == "sound" else "F"
    for no, context, target, char, zhuyin, alt, tags in dataset:
        q_id = f"{year}-{type_code}-{no:03d}"
        rows.append({
            "id": q_id,
            "type": q_type,
            "year": year,
            "level": "國小",
            "no": no,
            "context": context,
            "target": target,
            "char": char,
            "zhuyin": zhuyin,
            "alt_answers": alt,
            "tags": tags,
            "enabled": True,
            "note": "",
        })
    return rows

